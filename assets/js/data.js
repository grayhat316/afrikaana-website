/* Small helpers used across pages */

AFRIKAANA.getDish = function (id) {
  return AFRIKAANA.dishes.find(function (d) {
    return d.id === id;
  });
};

AFRIKAANA.getCategory = function (id) {
  return AFRIKAANA.categories.find(function (c) {
    return c.id === id;
  });
};

AFRIKAANA.getPackage = function (id) {
  return AFRIKAANA.packages.find(function (p) {
    return p.id === id;
  });
};

AFRIKAANA.getPost = function (id) {
  return AFRIKAANA.posts.find(function (p) {
    return p.id === id;
  });
};

AFRIKAANA.dishesInCategory = function (catId) {
  return AFRIKAANA.dishes.filter(function (d) {
    return d.category === catId;
  });
};

AFRIKAANA.money = function (n) {
  return "KES " + Number(n).toLocaleString("en-KE");
};

AFRIKAANA.formatDate = function (iso) {
  const d = new Date(iso + "T00:00:00");
  const months = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
  ];
  return d.getDate() + " " + months[d.getMonth()] + " " + d.getFullYear();
};

/* Cart counts, read by the header on every page */
AFRIKAANA.cartCount = function () {
  try {
    const raw = localStorage.getItem("afrikaana_cart");
    if (!raw) return 0;
    const cart = JSON.parse(raw);
    return cart.reduce(function (n, line) {
      return n + line.qty;
    }, 0);
  } catch (e) {
    return 0;
  }
};